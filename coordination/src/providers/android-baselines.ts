/** Host-side store of saved Android device baselines.
 *
 * A baseline is the disk state of one stopped AVD, copied once into
 * `<storage>/baselines/<name>/<revision>/` with a manifest that records every file's size and
 * SHA-256, the device definition and data-partition size it was made from, and the identity of
 * the installed system image. It is published by one rename, never modified afterwards and
 * removed only as a whole. A lease gets its own copy; the emulator never opens the stored files.
 *
 * A qcow2 overlay records its backing file by path, and a saved overlay still names the device it
 * was captured from. A clone is therefore accepted only when every copied overlay's recorded
 * backing path is the clone's own copied base image; otherwise it would read another device's
 * live file. Saving and cloning fail closed when that cannot be arranged.
 *
 * The emulator uses a system-image version cache when deciding whether to recreate overlays.
 * The clone gets a fresh cache derived from the pinned image's build properties. */
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { ServiceError, object } from "../errors.ts";
import { BASELINE_NAME, BASELINE_REVISION } from "../control/templates.ts";
import type { BaselineReference } from "../control/templates.ts";
import { canonical, digest, integer, privateDirectory, readJson, saveJson, uuid } from "./mobile.ts";
import type { RecordValue } from "./mobile.ts";

export interface BaselineFile { path: string; bytes: number; sha256: string }
export interface BaselineManifest {
  version: 1; id: string; name: string; revision: string; createdAt: number; machineId: string;
  arch: string; device: Record<string, string>; diskGiB: number;
  systemImage: { sourceProperties: string | null; buildProp: string | null };
  files: BaselineFile[]; bytes: number; digest: string;
}
/** What leaves the host: identity, binding and size. Never a path. */
export interface PublicBaseline {
  id: string; name: string; revision: string; digest: string; arch: string; device: Record<string, string>;
  diskGiB: number; bytes: number; files: number; createdAt: number; sourceMachineId: string;
  stale: boolean; staleReason?: string;
}
export interface BaselineBinding { arch: string; device: Record<string, string>; diskGiB: number }

/** Regenerated by the emulator or avdmanager for each AVD, or tied to one launch. The fresh AVD
 * keeps its own; none of them carries prepared guest state. */
const EXCLUDED_FILES = new Set(["config.ini", "hardware-qemu.ini", "emu-launch-params.txt", "read-snapshot.txt", "bootcompleted.ini",
  "emulator-user.ini", "quickbootChoice.ini", "AVD.conf", "version_num.cache", "multiinstance.lock"]);
/** Quick-boot snapshots are never used by a supervised launch (`-no-snapshot`) and are emulator-version specific. */
const EXCLUDED_DIRECTORIES = new Set(["snapshots", "tmpAdbCmds"]);
const MAX_FILES = 4096, MAX_DEPTH = 8, CHUNK = 1 << 20, MAX_BASELINES = 100;
const ZERO = Buffer.alloc(CHUNK);
const refuse = (message: string, code: string): never => { throw new ServiceError(message, 409, { code }); };
const identity = (stat: fs.BigIntStats): string => [stat.dev, stat.ino, stat.size, stat.mtimeNs, stat.ctimeNs].join("/");
function excluded(name: string): boolean { return EXCLUDED_FILES.has(name) || name.endsWith(".lock") || name.endsWith(".log") || name.endsWith(".tmp"); }
function readImageMetadata(file: string, limit: number): Buffer | null {
  let fd: number;
  try { fd = fs.openSync(file, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return null; throw error; }
  try {
    const stat = fs.fstatSync(fd);
    if (!stat.isFile() || stat.size > limit) return null;
    return fs.readFileSync(fd);
  } finally { fs.closeSync(fd); }
}
const metadataDigest = (data: Buffer | null): string | null =>
  data === null ? null : createHash("sha256").update(data).digest("hex");
const BUILD_PROP_LIMIT = 4 << 20;
function imageDirectory(sdk: string, systemImage: string): string { return path.join(sdk, ...systemImage.split(";")); }
function buildProperties(directory: string): Buffer | null {
  return readImageMetadata(path.join(directory, "build.prop"), BUILD_PROP_LIMIT);
}
/** Identity of the installed system image a baseline was made from. The package path alone does
 * not change when the SDK manager replaces an image in place; its package and build metadata do. */
export function systemImageIdentity(sdk: string, systemImage: string): BaselineManifest["systemImage"] | undefined {
  const directory = imageDirectory(sdk, systemImage);
  try { if (!fs.statSync(directory).isDirectory()) return undefined; } catch { return undefined; }
  return { sourceProperties: metadataDigest(readImageMetadata(path.join(directory, "source.properties"), 1 << 20)),
    buildProp: metadataDigest(buildProperties(directory)) };
}
/** QEMU recreates qcow2 disks when this cache is missing or differs from the system image.
 * Derive it from the verified build.prop so previously saved baselines work without a new digest.
 * The emulator reads the incremental property as a signed int and uses -1 when unavailable. */
function restoreVersionCache(avd: string, build: Buffer | null): void {
  const match = /^\s*ro\.build\.version\.incremental\s*=([^\r\n]*)/m.exec(build?.toString("utf8") ?? "");
  const value = match?.[1]?.trim() ?? "";
  const parsed = /^[+-]?\d+$/.test(value) ? Number(value) : -1;
  const version = parsed >= -2147483648 && parsed <= 2147483647 ? parsed : -1;
  const fd = fs.openSync(path.join(avd, "version_num.cache"), "wx", 0o600);
  try { fs.writeFileSync(fd, `${version}\n`); fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
  syncDirectory(avd);
}
function contentDigest(manifest: Pick<BaselineManifest, "arch" | "device" | "diskGiB" | "systemImage" | "files">): string {
  return digest({ version: 1, arch: manifest.arch, device: manifest.device, diskGiB: manifest.diskGiB, systemImage: manifest.systemImage, files: manifest.files });
}
/** One pass: hash every byte and write the copy, leaving holes where the source reads as zeros. */
async function sparseCopy(source: string, target: string, authorized: () => boolean): Promise<{ bytes: number; sha256: string }> {
  const input = await fs.promises.open(source, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
  try {
    const before = await input.stat({ bigint: true });
    if (!before.isFile()) refuse("A baseline holds regular files only.", "baseline_source_unsupported");
    const output = await fs.promises.open(target, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_NOFOLLOW, 0o600);
    try {
      const hash = createHash("sha256"), buffer = Buffer.allocUnsafe(CHUNK), size = Number(before.size);
      let position = 0;
      while (position < size) {
        if (!authorized()) throw new ServiceError("Baseline work lost its authorization.", 410);
        const { bytesRead } = await input.read(buffer, 0, Math.min(CHUNK, size - position), position);
        if (!bytesRead) refuse("A device file shrank while it was being copied.", "baseline_source_changed");
        const chunk = buffer.subarray(0, bytesRead);
        hash.update(chunk);
        if (chunk.compare(ZERO, 0, bytesRead) !== 0) {
          let written = 0;
          while (written < bytesRead) written += (await output.write(chunk, written, bytesRead - written, position + written)).bytesWritten;
        }
        position += bytesRead;
      }
      await output.truncate(size); await output.sync();
      // The source must be the same unchanged file at the end of the copy, by descriptor and by name.
      const after = await input.stat({ bigint: true }), named = await fs.promises.lstat(source, { bigint: true });
      if (identity(after) !== identity(before) || identity(named) !== identity(before)) refuse("A device file changed while it was being copied.", "baseline_source_changed");
      return { bytes: size, sha256: hash.digest("hex") };
    } finally { await output.close(); }
  } finally { await input.close(); }
}
async function hashFile(file: string): Promise<{ bytes: number; sha256: string; identity: string }> {
  const input = await fs.promises.open(file, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
  try {
    const before = await input.stat({ bigint: true });
    if (!before.isFile()) refuse("A stored baseline file is not a regular file.", "baseline_corrupt");
    const hash = createHash("sha256"), buffer = Buffer.allocUnsafe(CHUNK), size = Number(before.size);
    for (let position = 0; position < size;) {
      const { bytesRead } = await input.read(buffer, 0, Math.min(CHUNK, size - position), position);
      if (!bytesRead) break;
      hash.update(buffer.subarray(0, bytesRead)); position += bytesRead;
    }
    return { bytes: size, sha256: hash.digest("hex"), identity: identity(before) };
  } finally { await input.close(); }
}
const OVERLAY = ".qcow2";
/** The backing file a qcow2 image records in its header, or null when it has none. Anything that
 * is not a readable qcow2 header is refused: an overlay that cannot be inspected cannot be proven
 * self-contained. Layout per the qcow2 specification: magic, version, then the backing file's
 * offset (u64) and length (u32), all big-endian. */
export function overlayBacking(file: string): string | null {
  const fd = fs.openSync(file, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
  try {
    const size = fs.fstatSync(fd).size, header = Buffer.alloc(20);
    if (size < 20 || fs.readSync(fd, header, 0, 20, 0) !== 20 || header.readUInt32BE(0) !== 0x514649fb || ![2, 3].includes(header.readUInt32BE(4))) return refuse("A device overlay is not a readable qcow2 image.", "baseline_overlay_unsupported");
    const offset = header.readBigUInt64BE(8), length = header.readUInt32BE(16);
    if (!length) return null;
    if (length > 1023 || offset < 20n || offset + BigInt(length) > BigInt(size)) return refuse("A device overlay records an invalid backing file.", "baseline_overlay_unsupported");
    const name = Buffer.alloc(length);
    if (fs.readSync(fd, name, 0, length, Number(offset)) !== length || name.includes(0)) return refuse("A device overlay records an invalid backing file.", "baseline_overlay_unsupported");
    return name.toString("utf8");
  } finally { fs.closeSync(fd); }
}
function syncDirectory(directory: string): void { const fd = fs.openSync(directory, fs.constants.O_RDONLY); try { fs.fsyncSync(fd); } finally { fs.closeSync(fd); } }
function reference(value: { name: unknown; revision: unknown }): { name: string; revision: string } {
  if (typeof value.name !== "string" || BASELINE_NAME.exec(value.name)?.[0] !== value.name || typeof value.revision !== "string" || BASELINE_REVISION.exec(value.revision)?.[0] !== value.revision) throw new ServiceError("Invalid baseline name or revision.", 400);
  return { name: value.name, revision: value.revision };
}

export class BaselineStore {
  readonly root: string;
  /** Per stored baseline: the file identities under which its full digest was last verified. */
  private readonly verified = new Map<string, Map<string, string>>();
  constructor(storage: string, readonly sdk: string) {
    if (!path.isAbsolute(storage) || !path.isAbsolute(sdk)) throw new ServiceError("Baseline storage needs absolute paths.", 400);
    this.root = path.join(storage, "baselines");
  }
  private directory(name: string, revision: string): string { return path.join(this.root, name, revision); }
  /** A stored manifest, checked against its own recorded digest. */
  manifest(name: string, revision: string): BaselineManifest | undefined {
    const key = reference({ name, revision }), raw = readJson(path.join(this.directory(key.name, key.revision), "manifest.json"));
    if (!raw) return undefined;
    const files = Array.isArray(raw.files) ? raw.files.map(item => { const f = object(item); return { path: String(f.path), bytes: integer(f.bytes, "baseline file size", 0, Number.MAX_SAFE_INTEGER), sha256: String(f.sha256) }; }) : [];
    const system = object(raw.systemImage), device = object(raw.device) as Record<string, string>;
    const manifest: BaselineManifest = { version: 1, id: uuid(raw.id), name: String(raw.name), revision: String(raw.revision), createdAt: Number(raw.createdAt), machineId: uuid(raw.machineId),
      arch: String(raw.arch), device, diskGiB: integer(raw.diskGiB, "baseline disk size", 1, 2 ** 30),
      systemImage: { sourceProperties: system.sourceProperties === null ? null : String(system.sourceProperties), buildProp: system.buildProp === null ? null : String(system.buildProp) },
      files, bytes: integer(raw.bytes, "baseline size", 0, Number.MAX_SAFE_INTEGER), digest: String(raw.digest) };
    if (raw.version !== 1 || manifest.name !== key.name || manifest.revision !== key.revision || !files.length || files.length > MAX_FILES ||
      files.some(f => !/^[a-f0-9]{64}$/.test(f.sha256) || path.isAbsolute(f.path) || f.path.split("/").some(part => !part || part === "." || part === "..")) ||
      files.reduce((total, f) => total + f.bytes, 0) !== manifest.bytes || contentDigest(manifest) !== manifest.digest) refuse("A stored baseline manifest is invalid.", "baseline_corrupt");
    return manifest;
  }
  /** Why a baseline no longer matches this host's installed system image; undefined when current. */
  stale(manifest: BaselineManifest): string | undefined {
    const current = systemImageIdentity(this.sdk, String(manifest.device.systemImage));
    if (!current) return "Its system image is no longer installed on this host.";
    if (canonical(current) !== canonical(manifest.systemImage)) return "The installed system image changed after this baseline was saved.";
    return undefined;
  }
  view(manifest: BaselineManifest): PublicBaseline {
    const reason = this.stale(manifest);
    return { id: manifest.id, name: manifest.name, revision: manifest.revision, digest: manifest.digest, arch: manifest.arch, device: manifest.device, diskGiB: manifest.diskGiB,
      bytes: manifest.bytes, files: manifest.files.length, createdAt: manifest.createdAt, sourceMachineId: manifest.machineId, stale: reason !== undefined, ...(reason ? { staleReason: reason } : {}) };
  }
  /** Every published baseline. An unreadable entry is skipped, never repaired. */
  list(): PublicBaseline[] {
    const result: PublicBaseline[] = [];
    let names: string[];
    try { names = fs.readdirSync(this.root).sort(); } catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return result; throw error; }
    for (const name of names) {
      if (BASELINE_NAME.exec(name)?.[0] !== name) continue;
      let revisions: string[];
      try { revisions = fs.readdirSync(path.join(this.root, name)).sort(); } catch { continue; }
      for (const revision of revisions) {
        if (BASELINE_REVISION.exec(revision)?.[0] !== revision || result.length >= MAX_BASELINES) continue;
        try { const manifest = this.manifest(name, revision); if (manifest) result.push(this.view(manifest)); } catch { /* Left for the operator to inspect. */ }
      }
    }
    return result;
  }
  /** The baseline a pinned template names, or a refusal: missing, another digest, another device
   * definition or data size, or stale against the installed system image. */
  resolve(wanted: BaselineReference, binding: BaselineBinding): BaselineManifest {
    const manifest = this.manifest(wanted.name, wanted.revision);
    if (!manifest) return refuse("The template's baseline is not stored on this host.", "baseline_missing");
    if (manifest.digest !== wanted.digest) refuse("The stored baseline differs from the digest the template pins.", "baseline_mismatch");
    if (manifest.arch !== binding.arch || canonical(manifest.device) !== canonical(binding.device)) refuse("The baseline was made from another system image or device profile.", "baseline_stale");
    if (manifest.diskGiB !== binding.diskGiB) refuse("The baseline was made with another data partition size.", "baseline_mismatch");
    const reason = this.stale(manifest);
    if (reason) refuse(reason, "baseline_stale");
    return manifest;
  }
  private walk(directory: string, relative = "", depth = 0, found: string[] = []): string[] {
    if (depth > MAX_DEPTH) refuse("The device directory is nested too deeply to capture.", "baseline_source_unsupported");
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
      const name = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink()) refuse("The device directory contains a link; refusing to capture it.", "baseline_source_unsupported");
      if (entry.isDirectory()) { if (!EXCLUDED_DIRECTORIES.has(entry.name) && !entry.name.endsWith(".lock")) this.walk(path.join(directory, entry.name), name, depth + 1, found); continue; }
      if (!entry.isFile() || excluded(entry.name)) continue;
      found.push(name);
      if (found.length > MAX_FILES) refuse("The device directory holds too many files to capture.", "baseline_source_unsupported");
    }
    return found;
  }
  /** Copies a stopped device's disk state into a new immutable baseline. The caller holds the
   * assignment lock and has proven the device stopped. Nothing is visible until the final rename;
   * a failure before it removes the staging directory and leaves no baseline. */
  async save(request: { id: string; name: string; revision: string }, source: { avd: string; machineId: string; rebase: boolean } & BaselineBinding, authorized: () => boolean): Promise<PublicBaseline> {
    const id = uuid(request.id), key = reference(request), target = this.directory(key.name, key.revision);
    const existing = this.manifest(key.name, key.revision);
    if (existing) {
      // A lost reply: the same save is already published.
      if (existing.id === id) return this.view(existing);
      refuse("A baseline with this name and revision already exists; save a new revision.", "baseline_exists");
    }
    if (fs.existsSync(target)) refuse("Baseline storage for this name and revision is occupied; inspect it.", "baseline_exists");
    const system = systemImageIdentity(this.sdk, String(source.device.systemImage));
    if (!system) return refuse("The device's system image is not installed on this host.", "baseline_stale");
    privateDirectory(this.root);
    const staging = path.join(this.root, `.staging-${id}`);
    if (fs.existsSync(staging)) refuse("An earlier save of this baseline was interrupted; remove it before saving again.", "baseline_exists");
    // Every overlay must be one a clone can make self-contained: its backing file is its own base
    // image inside this device, that base is captured with it, and the host can rebase the copy.
    const captured = this.walk(source.avd);
    for (const relative of captured.filter(name => name.endsWith(OVERLAY))) {
      const backing = overlayBacking(path.join(source.avd, relative));
      if (backing === null) continue;
      const base = relative.slice(0, -OVERLAY.length);
      if (!captured.includes(base) || path.resolve(path.dirname(path.join(source.avd, relative)), backing) !== path.join(source.avd, base)) refuse("A device overlay is backed by a file outside this device's own captured images.", "baseline_overlay_unsupported");
      if (path.isAbsolute(backing) && !source.rebase) refuse("This host cannot rebase a copied overlay (the SDK has no emulator/qemu-img), so the baseline could not be used.", "baseline_overlay_unsupported");
    }
    fs.mkdirSync(staging, { mode: 0o700 });
    try {
      const files: BaselineFile[] = [];
      for (const relative of captured) {
        const destination = path.join(staging, "files", relative);
        fs.mkdirSync(path.dirname(destination), { recursive: true, mode: 0o700 });
        files.push({ path: relative, ...await sparseCopy(path.join(source.avd, relative), destination, authorized) });
        fs.chmodSync(destination, 0o400);
      }
      if (!files.length) refuse("The device has no disk state to capture; boot and prepare it first.", "baseline_source_unsupported");
      const body = { arch: source.arch, device: source.device, diskGiB: source.diskGiB, systemImage: system, files };
      const manifest: BaselineManifest = { version: 1, id, name: key.name, revision: key.revision, createdAt: Math.floor(Date.now() / 1000), machineId: uuid(source.machineId), ...body,
        bytes: files.reduce((total, f) => total + f.bytes, 0), digest: contentDigest(body) };
      saveJson(path.join(staging, "manifest.json"), manifest);
      if (!authorized()) throw new ServiceError("Baseline work lost its authorization.", 410);
      privateDirectory(path.dirname(target));
      // One rename publishes the whole baseline; rename never replaces an existing directory with content.
      if (fs.existsSync(target)) refuse("A baseline with this name and revision already exists; save a new revision.", "baseline_exists");
      fs.renameSync(staging, target);
      for (const directory of [...this.directories(target)].reverse()) fs.chmodSync(directory, 0o500);
      syncDirectory(path.dirname(target)); syncDirectory(this.root);
      return this.view(manifest);
    } catch (error) {
      // Not yet published: the staging directory holds nothing another reader can see.
      if (fs.existsSync(staging)) fs.rmSync(staging, { recursive: true, force: true });
      throw error;
    }
  }
  private directories(top: string, found: string[] = []): string[] {
    found.push(top);
    for (const entry of fs.readdirSync(top, { withFileTypes: true })) if (entry.isDirectory()) this.directories(path.join(top, entry.name), found);
    return found;
  }
  /** Full digest check of the stored files, repeated only when a file's identity changed. */
  private async verify(manifest: BaselineManifest): Promise<void> {
    const key = `${manifest.name}/${manifest.revision}/${manifest.digest}`, directory = path.join(this.directory(manifest.name, manifest.revision), "files");
    const known = this.verified.get(key);
    if (known && manifest.files.every(file => { try { return known.get(file.path) === identity(fs.lstatSync(path.join(directory, file.path), { bigint: true })); } catch { return false; } })) return;
    this.verified.delete(key);
    const identities = new Map<string, string>();
    for (const file of manifest.files) {
      const actual = await hashFile(path.join(directory, file.path));
      if (actual.bytes !== file.bytes || actual.sha256 !== file.sha256) refuse("A stored baseline file no longer matches its recorded digest.", "baseline_corrupt");
      identities.set(file.path, actual.identity);
    }
    this.verified.set(key, identities);
  }
  /** Everything that can refuse a baseline, checked before a device is created for it: presence,
   * pinned digest, device binding, staleness and the stored files' own digests. */
  async check(wanted: BaselineReference, binding: BaselineBinding): Promise<BaselineManifest> {
    const manifest = this.resolve(wanted, binding);
    await this.verify(manifest);
    return manifest;
  }
  /** Gives a fresh AVD its own copy of the baseline's files. The stored files are only read. A
   * copy-on-write clone is used where the filesystem has one; otherwise each file is copied and
   * its digest rechecked in the same pass. */
  async clone(wanted: BaselineReference, binding: BaselineBinding, avd: string, rebase: ((overlay: string, base: string) => Promise<void>) | undefined, authorized: () => boolean = () => true): Promise<RecordValue> {
    const manifest = await this.check(wanted, binding), directory = path.join(this.directory(manifest.name, manifest.revision), "files");
    let reflinked = 0;
    for (const file of manifest.files) {
      if (!authorized()) throw new ServiceError("Baseline clone lost its authorization.", 410);
      const source = path.join(directory, file.path), destination = path.join(avd, file.path);
      if (path.relative(avd, destination).startsWith("..")) refuse("A baseline file path leaves the device directory.", "baseline_corrupt");
      fs.mkdirSync(path.dirname(destination), { recursive: true, mode: 0o700 });
      // A fresh AVD may already hold its own initial image under this name; the baseline's replaces it.
      fs.rmSync(destination, { force: true });
      let cloned = false;
      try { await fs.promises.copyFile(source, destination, fs.constants.COPYFILE_EXCL | fs.constants.COPYFILE_FICLONE_FORCE); cloned = true; reflinked++; }
      catch { fs.rmSync(destination, { force: true }); }
      if (!cloned) {
        const copied = await sparseCopy(source, destination, authorized);
        if (copied.bytes !== file.bytes || copied.sha256 !== file.sha256) refuse("A stored baseline file no longer matches its recorded digest.", "baseline_corrupt");
      }
      fs.chmodSync(destination, 0o600);
    }
    // The stored files must still be the verified ones after the copy.
    await this.verify(manifest);
    // No copied overlay may read anything but the clone's own copied base. A saved overlay names
    // the device it was captured from, so it is rebased, and the recorded path is read back.
    const copied = new Set(manifest.files.map(file => file.path)), relocated: string[] = [];
    const overlays = [...copied].filter(name => name.endsWith(OVERLAY));
    for (const relative of overlays) {
      const overlay = path.join(avd, relative), base = path.join(avd, relative.slice(0, -OVERLAY.length));
      const own = (): boolean => { const backing = overlayBacking(overlay); return backing === null || path.resolve(path.dirname(overlay), backing) === base && copied.has(relative.slice(0, -OVERLAY.length)); };
      if (own()) continue;
      if (!copied.has(relative.slice(0, -OVERLAY.length))) refuse("A stored overlay has no base image of its own in this baseline.", "baseline_overlay_unsupported");
      if (!rebase) refuse("This host cannot rebase a copied overlay (the SDK has no emulator/qemu-img); the device is not booted from another device's file.", "baseline_overlay_unsupported");
      await rebase!(overlay, base);
      if (!own()) refuse("A copied overlay still records a backing file outside this device after the rebase.", "baseline_overlay_unsupported");
      relocated.push(relative);
    }
    if (overlays.length) {
      if (!authorized()) throw new ServiceError("Baseline clone lost its authorization.", 410);
      const build = buildProperties(imageDirectory(this.sdk, String(manifest.device.systemImage)));
      if (metadataDigest(build) !== manifest.systemImage.buildProp) refuse("The installed system image changed while restoring the baseline.", "baseline_stale");
      restoreVersionCache(avd, build);
    }
    return { name: manifest.name, revision: manifest.revision, digest: manifest.digest, files: manifest.files.map(file => file.path), bytes: manifest.bytes, reflinked, relocated };
  }
  /** Removes one baseline as a whole, or what an interrupted save of it left behind. */
  remove(request: { id: string; name: string; revision: string }): RecordValue {
    const id = uuid(request.id), key = reference(request), target = this.directory(key.name, key.revision);
    const staging = path.join(this.root, `.staging-${id}`), quarantine = path.join(this.root, `.removing-${id}`);
    if (fs.existsSync(staging)) fs.rmSync(staging, { recursive: true, force: true });
    if (fs.existsSync(target)) {
      const manifest = this.manifest(key.name, key.revision);
      if (!manifest || manifest.id !== id) refuse("The stored baseline belongs to another save; it was not removed.", "baseline_mismatch");
      if (fs.existsSync(quarantine)) refuse("Baseline removal quarantine is occupied; inspect it.", "baseline_exists");
      for (const directory of this.directories(target)) fs.chmodSync(directory, 0o700);
      fs.renameSync(target, quarantine);
    }
    if (fs.existsSync(quarantine)) { for (const directory of this.directories(quarantine)) fs.chmodSync(directory, 0o700); fs.rmSync(quarantine, { recursive: true }); }
    try { fs.rmdirSync(path.dirname(target)); } catch { /* Other revisions remain, or it was never created. */ }
    for (const cached of [...this.verified.keys()]) if (cached.startsWith(`${key.name}/${key.revision}/`)) this.verified.delete(cached);
    if (fs.existsSync(this.root)) syncDirectory(this.root);
    return { removed: true };
  }
}
